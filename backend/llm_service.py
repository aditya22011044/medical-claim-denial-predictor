"""LLM service: turns ML predictions into a professional, structured recommendation.

Model-fallback policy:

* A single NVIDIA NIM API key (``NVIDIA_API_KEY``) is used against the OpenAI-compatible
  endpoint ``https://integrate.api.nvidia.com/v1``.
* An **ordered chain of models** is configured in ``config.get_llm_targets()``. The head
  of the chain is tried first; if it cannot serve the request the next model is tried,
  and so on.
* On an **authentication / permission / connection / timeout** failure, or a **quota /
  billing failure** (``insufficient_quota`` / "no credits remaining"), the model is
  treated as unavailable and the next model in the chain is tried.
* On a **transient rate-limit (HTTP 429)** the *same* model is retried honouring the
  ``Retry-After`` header and exponential back-off before falling through.
* If a model does not support JSON mode or returns malformed JSON, the call is retried
  once without ``response_format`` before falling through to the next model.
* If every model fails, the LLM is gracefully disabled: ML predictions stay available
  and the API returns a clear explanation instead of an exception.

API keys are never logged and never returned to the client.
"""
from __future__ import annotations

import json
import time
from typing import Any, Optional

from openai import (APIConnectionError, APIStatusError, APITimeoutError,
                    AuthenticationError, OpenAI, RateLimitError)

from . import config


class LLMUnavailable(RuntimeError):
    """Raised when no configured key can serve a request."""


SYSTEM_PROMPT = """You are an AI Medical Claims Analysis and Reimbursement Advisory Assistant.

Analyze medical claims using predictions generated by trained ML models and historical payer intelligence.

The ML models were trained on a FEATURE-SELECTED top-5 subset of claim attributes ONLY:
  documentation_completeness, cpt_code, primary_icd10_dx, claim_amount_usd, auth_status.
Everything else in the payload is advisory context, not a model input.

You receive:
- Claim information (including the 5 model features).
- Denial probability and approval probability.
- Predicted claim status and risk level.
- Predicted denial reason and X12 code.
- Expected recovery amount (predicted for denied claims).
- Historical payer statistics.
- Relevant model-supported risk indicators.

Generate an actionable report containing:
1. Executive Summary.
2. Claim Risk Assessment.
3. Predicted Denial Reason.
4. Important Risk Factors.
5. Recommended Actions Before Submission.
6. Billing Code Review.
7. Reimbursement Insights.
8. Final Recommendation.

Rules:
- Never modify ML predictions.
- Never present predictions as confirmed outcomes.
- Never invent denial codes or payer policies.
- Never recommend changing codes without supporting documentation.
- Never fabricate medical documentation.
- Clearly distinguish historical statistics from claim-specific predictions.
- Mention missing information when necessary.
- Never guarantee claim approval.
- Use simple, professional language.
- Return structured JSON suitable for a Web UI / dashboard rendering.

Return ONLY a JSON object with exactly these keys:
{
  "executive_summary": string,
  "claim_risk_assessment": string,
  "predicted_denial_reason": string,
  "important_risk_factors": [string, ...],
  "recommended_actions": [string, ...],
  "billing_code_review": string,
  "reimbursement_insights": string,
  "final_recommendation": one of
        "Ready for submission after routine verification",
        "Review recommended before submission",
        "High-priority review required before submission"
}
"""

REPORT_KEYS = [
    "executive_summary", "claim_risk_assessment", "predicted_denial_reason",
    "important_risk_factors", "recommended_actions", "billing_code_review",
    "reimbursement_insights", "final_recommendation",
]
VALID_RECOMMENDATIONS = {
    "Ready for submission after routine verification",
    "Review recommended before submission",
    "High-priority review required before submission",
}


def llm_available() -> bool:
    return len(config.get_llm_targets()) > 0


def configured_key_count() -> int:
    """Number of configured LLM call targets (models in the fallback chain)."""
    return len(config.get_llm_targets())


def _retry_after_seconds(exc: Exception) -> Optional[float]:
    resp = getattr(exc, "response", None)
    if resp is not None:
        header = getattr(resp, "headers", {}) or {}
        value = header.get("retry-after") or header.get("Retry-After")
        if value:
            try:
                return float(value)
            except (TypeError, ValueError):
                return None
    return None


def _make_client(target: dict) -> OpenAI:
    """Build an OpenAI-compatible client for one model-fallback target."""
    return OpenAI(
        api_key=target["api_key"],
        base_url=target["base_url"],
        timeout=config.LLM_TIMEOUT_SECONDS,
        max_retries=0,  # we own the retry/fallback logic
    )


def _message_text(message: Any) -> str:
    """Return the textual content of an assistant message.

    Handles providers that return ``content`` as a list of parts, and reasoning
    models that expose the answer through ``reasoning_content``.
    """
    content = getattr(message, "content", None)
    if isinstance(content, list):
        content = "".join(
            part.get("text", "") for part in content if isinstance(part, dict))
    if not content:
        content = getattr(message, "reasoning_content", None)
    return content or ""


def _extract_json(text: str) -> dict:
    """Parse a JSON object out of a possibly fenced / chatty model response."""
    if not text or not text.strip():
        raise json.JSONDecodeError("empty response", text or "", 0)
    cleaned = text.strip()
    if cleaned.startswith("```"):
        # drop the opening fence (e.g. ```json) and the closing fence
        body = cleaned.split("\n", 1)[1] if "\n" in cleaned else cleaned
        if body.rstrip().endswith("```"):
            body = body.rstrip()[:-3]
        cleaned = body.strip()
        if cleaned[:4].lower() == "json":
            cleaned = cleaned[4:].lstrip()
    start, end = cleaned.find("{"), cleaned.rfind("}")
    if start == -1 or end <= start:
        raise json.JSONDecodeError("no JSON object found", cleaned, 0)
    return json.loads(cleaned[start:end + 1])


def _validate_report(raw: dict) -> dict:
    """Normalise the LLM output and guarantee the required structure."""
    report = {k: raw.get(k) for k in REPORT_KEYS}
    if isinstance(report.get("important_risk_factors"), str):
        report["important_risk_factors"] = [report["important_risk_factors"]]
    if isinstance(report.get("recommended_actions"), str):
        report["recommended_actions"] = [report["recommended_actions"]]
    report["important_risk_factors"] = report.get("important_risk_factors") or []
    report["recommended_actions"] = report.get("recommended_actions") or []
    if report.get("final_recommendation") not in VALID_RECOMMENDATIONS:
        # never fabricate a verdict; fall back to the safest wording
        report["final_recommendation"] = "Review recommended before submission"
    report["_source"] = "llm"
    return report


def _pct(value: Any) -> str:
    return f"{value * 100:.1f}%" if isinstance(value, (int, float)) else "n/a"


def _usd(value: Any) -> str:
    return f"${value:,.2f}" if isinstance(value, (int, float)) else "n/a"


def build_fallback_report(payload: dict) -> dict:
    """Deterministically synthesise the 8-section report from the ML payload.

    Used when no LLM key can serve the request, so the UI **always** renders a
    complete recommendation instead of an error. It is purely rule/template based -
    no network and no API key required - and it never invents numbers: every figure
    is taken from the ML predictions or the historical payer statistics already in
    the payload.
    """
    claim = payload.get("claim", {}) or {}
    ml = payload.get("ml_predictions", {}) or {}
    payer = payload.get("historical_payer_statistics", {}) or {}
    indicators = payload.get("model_supported_risk_indicators", []) or []

    cpt = claim.get("cpt_code") or "the submitted procedure"
    icd = claim.get("primary_icd10_dx") or "the submitted diagnosis"
    amount = claim.get("claim_amount_usd")
    doc = claim.get("documentation_completeness")
    auth = claim.get("auth_status") or "unknown"

    denial_p = ml.get("denial_probability")
    approval_p = ml.get("approval_probability")
    status = ml.get("predicted_status") or "Unknown"
    risk_level = ml.get("risk_level") or "Unknown"
    risk_score = ml.get("risk_score_0_100")
    reason = ml.get("predicted_denial_reason")
    x12 = ml.get("predicted_x12_code")
    confidence = ml.get("denial_reason_confidence")
    alternatives = ml.get("denial_reason_alternatives") or []
    recovery = ml.get("predicted_recovery_usd")

    payer_name = payer.get("payer_type") or "(not provided)"
    payer_rate = payer.get("historical_denial_rate")
    overall_rate = payer.get("overall_denial_rate")
    payer_reason = payer.get("top_denial_reason")
    payer_code = payer.get("top_denial_code")
    payer_avg_recovery = payer.get("avg_recovery_usd")

    # ---- 1. Executive Summary -------------------------------------------------
    payer_sentence = ""
    if isinstance(payer_rate, (int, float)) and isinstance(overall_rate, (int, float)):
        comparison = ("above" if payer_rate > overall_rate else
                      "below" if payer_rate < overall_rate else "in line with")
        payer_sentence = (f" Payer {payer_name} historically denies {_pct(payer_rate)} of claims, "
                          f"{comparison} the {_pct(overall_rate)} portfolio average.")
    executive_summary = (
        f"This claim (CPT {cpt}, primary diagnosis {icd}, billed {_usd(amount)}) is predicted "
        f"to be {status} with a denial probability of {_pct(denial_p)} "
        f"(approval probability {_pct(approval_p)}). The model places it in the {risk_level} "
        f"risk band with a risk score of {risk_score}/100.{payer_sentence} "
        "These are model estimates based on historical claim patterns, not a confirmed outcome."
    )

    # ---- 2. Claim Risk Assessment --------------------------------------------
    assess_parts = [
        f"Overall risk score {risk_score}/100 ({risk_level}).",
        f"The most influential model inputs are documentation completeness ({doc}), "
        f"procedure code ({cpt}) and primary diagnosis ({icd}).",
    ]
    if auth == "not_obtained":
        assess_parts.append("Prior authorisation was required but has not been obtained, "
                            "which is a strong denial driver.")
    elif auth == "unknown":
        assess_parts.append("Prior-authorisation requirement is unconfirmed.")
    claim_risk_assessment = " ".join(assess_parts)

    # ---- 3. Predicted Denial Reason ------------------------------------------
    if reason:
        predicted_denial_reason = (
            f"Most likely denial reason: {reason}"
            + (f" (representative X12 code {x12})" if x12 else "")
            + f", confidence {_pct(confidence)}."
        )
        if alternatives:
            alt_txt = "; ".join(
                f"{a.get('category')} ({_pct(a.get('probability'))})"
                for a in alternatives if isinstance(a, dict) and a.get("category"))
            if alt_txt:
                predicted_denial_reason += f" Alternative reasons considered: {alt_txt}."
    else:
        predicted_denial_reason = ("No single denial reason dominates for this claim; the denial "
                                   "risk is spread across the submitted attributes.")

    # ---- 4. Important Risk Factors -------------------------------------------
    important_risk_factors = [
        f"{ind.get('factor')}: {ind.get('detail')}"
        for ind in indicators
        if isinstance(ind, dict) and ind.get("direction") == "increases_risk"
    ]
    if not important_risk_factors:
        important_risk_factors = [
            "No single feature dominates; risk is driven by the combination of the five "
            "submitted attributes."]

    # ---- 5. Recommended Actions Before Submission ----------------------------
    actions: list[str] = []
    if isinstance(doc, (int, float)) and doc < 0.6:
        actions.append(f"Improve documentation completeness before submission (currently "
                       f"{doc:.2f}); attach the missing clinical notes and supporting documents.")
    if auth == "not_obtained":
        actions.append("Obtain prior authorisation before submitting - missing authorisation is a "
                       "leading and easily preventable denial cause.")
    elif auth == "unknown":
        actions.append("Confirm whether prior authorisation is required for this procedure and "
                       "obtain it before submission if so.")
    if isinstance(payer_rate, (int, float)) and isinstance(overall_rate, (int, float)) \
            and payer_rate > overall_rate:
        actions.append(f"Attach medical-necessity documentation: {payer_name} denies above the "
                       f"portfolio average ({_pct(payer_rate)} vs {_pct(overall_rate)}).")
    if risk_level == "High":
        actions.append("Route this claim to a senior coder for a pre-submission review.")
    actions.append("Verify the CPT/ICD pairing and confirm the billed amount matches the "
                   "documented services.")
    actions.append("Keep the claim packaged for a fast appeal in case it is denied.")

    # ---- 6. Billing Code Review ----------------------------------------------
    billing_code_review = (
        f"Submitted procedure {cpt} is paired with primary diagnosis {icd}. Confirm the two are "
        "medically compatible and clearly supported in the record. Do not change codes without "
        "supporting documentation."
    ) + (f" Historical denials for {payer_name} most often cite {payer_reason}"
         + (f" ({payer_code})" if payer_code else "") + "." if payer_reason else "")

    # ---- 7. Reimbursement Insights -------------------------------------------
    if isinstance(recovery, (int, float)):
        reimbursement_insights = (
            f"If this claim is denied and appealed, the expected recovery is {_usd(recovery)}.")
        if isinstance(payer_avg_recovery, (int, float)):
            reimbursement_insights += (f" {payer_name} historically recovers about "
                                       f"{_usd(payer_avg_recovery)} per denied claim.")
    else:
        reimbursement_insights = "Expected recovery could not be estimated for this claim."

    # ---- 8. Final Recommendation ---------------------------------------------
    if isinstance(risk_score, (int, float)) and risk_score >= 70:
        final = "High-priority review required before submission"
    elif isinstance(risk_score, (int, float)) and risk_score >= 40:
        final = "Review recommended before submission"
    else:
        final = "Ready for submission after routine verification"

    report = {
        "executive_summary": executive_summary,
        "claim_risk_assessment": claim_risk_assessment,
        "predicted_denial_reason": predicted_denial_reason,
        "important_risk_factors": important_risk_factors,
        "recommended_actions": actions,
        "billing_code_review": billing_code_review,
        "reimbursement_insights": reimbursement_insights,
        "final_recommendation": final,
        "_source": "local-rules",
    }
    return report


def generate_report(payload: dict) -> dict:
    """Call the first working model in the NVIDIA fallback chain.

    Models are tried in the configured order; a model is skipped on an
    authentication / permission / connection / quota failure or on malformed output.
    Raises ``LLMUnavailable`` only when every model in the chain fails.
    """
    targets = config.get_llm_targets()
    if not targets:
        raise LLMUnavailable("No LLM API key is configured (NVIDIA_API_KEY).")

    messages = [
        {"role": "system", "content": SYSTEM_PROMPT},
        {"role": "user", "content": json.dumps(payload, indent=2, default=str)},
    ]
    failures: list[str] = []

    for index, target in enumerate(targets, start=1):
        model = target["model"]
        client = _make_client(target)
        use_json_mode = True   # retried once without it if the model rejects it
        attempt = 0
        while True:
            try:
                kwargs: dict[str, Any] = {
                    "model": model,
                    "messages": messages,
                    "temperature": 0.2,
                    "max_tokens": 4096,
                }
                if use_json_mode:
                    kwargs["response_format"] = {"type": "json_object"}
                response = client.chat.completions.create(**kwargs)
                text = _message_text(response.choices[0].message)
                raw = _extract_json(text)
                # A valid JSON payload that is missing the report body is useless -
                # treat it as a failure so the next model in the chain is tried.
                if not isinstance(raw, dict) or not str(raw.get("executive_summary") or "").strip():
                    raise ValueError("incomplete report")
                report = _validate_report(raw)
                return {"model": response.model or model, "report": report}

            except RateLimitError as exc:
                low = str(exc).lower()
                # A quota / billing failure is permanent for this model - fall through
                # to the next model in the chain (the whole point of the fallback).
                if "insufficient_quota" in low or "no credits" in low or "exceeded your current quota" in low:
                    failures.append(f"model #{index} ({model}): quota/credits exhausted")
                    break
                # Transient rate limit: back off on the SAME model before falling through.
                wait = _retry_after_seconds(exc) or min(2 ** attempt, 30)
                if attempt >= config.LLM_MAX_RETRIES:
                    failures.append(f"model #{index} ({model}): rate limited after {attempt} retries")
                    break
                time.sleep(wait)
                attempt += 1

            except (AuthenticationError, PermissionError):
                failures.append(f"model #{index} ({model}): authentication failed")
                break

            except APITimeoutError:
                # A slow model is not worth retrying - fall through quickly.
                failures.append(f"model #{index} ({model}): request timed out")
                break

            except APIConnectionError:
                attempt += 1
                if attempt > config.LLM_MAX_RETRIES:
                    failures.append(f"model #{index} ({model}): connection error")
                    break
                time.sleep(min(2 ** attempt, 10))

            except APIStatusError as exc:
                text = str(exc).lower()
                # Some models reject response_format -> retry once without JSON mode.
                if use_json_mode and exc.status_code in (400, 404, 422) and "response_format" in text:
                    use_json_mode = False
                    continue
                failures.append(f"model #{index} ({model}): HTTP {exc.status_code}")
                break

            except (json.JSONDecodeError, ValueError):
                # Malformed / empty output: retry once without JSON mode, then fall through.
                if use_json_mode:
                    use_json_mode = False
                    continue
                failures.append(f"model #{index} ({model}): returned invalid JSON")
                break

    tried = len(targets)
    raise LLMUnavailable(
        f"All {tried} NVIDIA models in the fallback chain failed. "
        "ML predictions remain fully available. Tried: " + "; ".join(failures))
